<?php

declare(strict_types=1);

use App\Database\Migrations\CreateBloc2RecruitmentTables;
use App\Database\Migrations\CreateEntretienParticipantTable;
use App\Services\Bloc2\RecruitmentService;
use CodeIgniter\Boot;
use Config\Database;
use Config\Paths;

error_reporting(E_ALL);
ini_set('display_errors', '1');

define('ENVIRONMENT', 'testing');
define('CI_DEBUG', true);
define('HOMEPATH', dirname(__DIR__, 2) . DIRECTORY_SEPARATOR);
define('CONFIGPATH', HOMEPATH . 'app/Config/');
define('PUBLICPATH', HOMEPATH . 'public/');
require CONFIGPATH . 'Paths.php';
$paths = new Paths();
define('APPPATH', realpath($paths->appDirectory) . DIRECTORY_SEPARATOR);
define('ROOTPATH', HOMEPATH);
define('SYSTEMPATH', realpath($paths->systemDirectory) . DIRECTORY_SEPARATOR);
define('WRITEPATH', realpath($paths->writableDirectory) . DIRECTORY_SEPARATOR);
define('TESTPATH', HOMEPATH . 'tests/');
define('CIPATH', ROOTPATH);
define('FCPATH', PUBLICPATH);
define('SUPPORTPATH', TESTPATH . '_support/');
define('COMPOSER_PATH', '');
define('VENDORPATH', HOMEPATH . 'vendor/');
require SYSTEMPATH . 'Boot.php';
Boot::bootTest($paths);
require_once APPPATH . 'Database/Migrations/2026-10-22-100000_CreateBloc2RecruitmentTables.php';
require_once APPPATH . 'Database/Migrations/2026-10-22-110000_CreateEntretienParticipantTable.php';

$database = (string) getenv('BLOC2_TEST_PG_DATABASE');
$username = (string) getenv('BLOC2_TEST_PG_USER');
$password = (string) getenv('BLOC2_TEST_PG_PASSWORD');
$hostname = (string) (getenv('BLOC2_TEST_PG_HOST') ?: '127.0.0.1');
$port = (int) (getenv('BLOC2_TEST_PG_PORT') ?: 5432);

if ($database === '' || $username === '' || ! preg_match('/(test|demo)/i', $database)) {
    fwrite(STDERR, "Définissez BLOC2_TEST_PG_DATABASE (nom contenant test/demo), BLOC2_TEST_PG_USER et BLOC2_TEST_PG_PASSWORD.\n");
    exit(2);
}

$baseConfig = [
    'DBDriver' => 'Postgre', 'hostname' => $hostname, 'port' => $port,
    'database' => $database, 'username' => $username, 'password' => $password,
    'DBPrefix' => '', 'DBDebug' => true, 'schema' => 'public',
    'dateFormat' => ['date' => 'Y-m-d', 'datetime' => 'Y-m-d H:i:s', 'time' => 'H:i:s'],
];
$admin = Database::connect($baseConfig, false);
$schema = 'bloc2_test_' . bin2hex(random_bytes(6));
$quotedSchema = '"' . $schema . '"';
$admin->query("CREATE SCHEMA {$quotedSchema}");

$failure = null;
$tests = 0;
try {
    $testConfig = $baseConfig;
    $testConfig['schema'] = $schema;
    $db = Database::connect($testConfig, false);
    $db->query("SET search_path TO {$quotedSchema}");

    foreach ([
        'CREATE TABLE status (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code VARCHAR(50) UNIQUE NOT NULL, libelle VARCHAR(100), actif BOOLEAN DEFAULT TRUE)',
        'CREATE TABLE employe (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, matricule VARCHAR(20), nom VARCHAR(100), prenom VARCHAR(100), actif BOOLEAN DEFAULT TRUE)',
        'CREATE TABLE demande (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, intitule VARCHAR(150), status_id INTEGER REFERENCES status(id))',
        'CREATE TABLE validation (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, demande_id INTEGER REFERENCES demande(id), validateur_id INTEGER REFERENCES employe(id), status_id INTEGER REFERENCES status(id), commentaire TEXT, date_validation TIMESTAMP)',
    ] as $sql) {
        $db->query($sql);
    }

    (new CreateBloc2RecruitmentTables(Database::forge($db)))->up();
    (new CreateEntretienParticipantTable(Database::forge($db)))->up();

    $db->table('status')->insertBatch([
        ['id' => 1, 'code' => 'DIRECTION_validee', 'libelle' => 'Direction validée'],
        ['id' => 2, 'code' => 'RH_validee', 'libelle' => 'RH validée'],
    ]);
    $db->table('employe')->insertBatch([
        ['id' => 1, 'matricule' => 'RH-1', 'nom' => 'Rakoto', 'prenom' => 'Sofia', 'actif' => true],
        ['id' => 2, 'matricule' => 'MAN-1', 'nom' => 'Rabe', 'prenom' => 'Alain', 'actif' => true],
        ['id' => 3, 'matricule' => 'MAN-2', 'nom' => 'Raja', 'prenom' => 'Mina', 'actif' => true],
    ]);
    $db->table('demande')->insertBatch([
        ['id' => 1, 'intitule' => 'Analyste', 'status_id' => 1],
        ['id' => 2, 'intitule' => 'RH seulement', 'status_id' => 2],
    ]);
    $db->table('validation')->insertBatch([
        ['id' => 1, 'demande_id' => 1, 'validateur_id' => 2, 'status_id' => 1, 'commentaire' => 'Accord Direction'],
        ['id' => 2, 'demande_id' => 2, 'validateur_id' => 1, 'status_id' => 2, 'commentaire' => 'Avis RH'],
    ]);

    $assert = static function (bool $condition, string $message) use (&$tests): void {
        $tests++;
        if (! $condition) {
            throw new RuntimeException("ÉCHEC PostgreSQL #{$tests}: {$message}");
        }
    };
    $service = new RecruitmentService($db);

    $assert(array_column($service->approvedRequests(), 'id') === [1], 'approbation Direction stricte');
    $assert(! $service->saveOffer(['demande_recrutement_id' => 2, 'titre' => 'Interdite'])['ok'], 'demande RH refusée');
    $assert($service->saveOffer(['demande_recrutement_id' => 1, 'titre' => 'Analyste', 'date_cloture' => '2099-12-31'])['ok'], 'offre créée');
    $assert($service->publishOffer(1)['ok'], 'offre publiée');
    $assert($service->saveCandidate(['nom' => 'Andry', 'prenom' => 'Jean', 'email' => 'jean.pg@example.test'])['ok'], 'candidat créé');
    $assert($service->saveApplication(['candidat_id' => 1, 'offre_emploi_id' => 1])['ok'], 'candidature créée');
    $assert(! $service->saveApplication(['candidat_id' => 1, 'offre_emploi_id' => 1])['ok'], 'candidature double refusée');
    $assert($service->changeApplicationStatus(1, ['statut' => 'PRESELECTIONNEE'])['ok'], 'présélection');

    $assert($service->saveInterview(['candidature_id' => 1, 'date_entretien' => '2099-01-10T09:00', 'type_entretien' => 'RH', 'lieu' => 'A', 'participant_ids' => [1, 2]])['ok'], 'entretien RH');
    $assert($service->changeInterviewStatus(1, ['statut' => 'REALISE', 'compte_rendu' => 'Concluant'])['ok'], 'entretien RH réalisé');
    $assert($service->saveInterview(['candidature_id' => 1, 'date_entretien' => '2099-01-11T09:00', 'type_entretien' => 'Technique', 'lieu' => 'B', 'participant_ids' => [2]])['ok'], 'entretien multiple et type normalisé');
    $assert($service->changeInterviewStatus(2, ['statut' => 'ANNULE'])['ok'], 'annulation');
    $assert($service->saveInterview(['candidature_id' => 1, 'date_entretien' => '2099-01-12T09:00', 'type_entretien' => 'TECHNIQUE', 'lieu' => 'C', 'participant_ids' => [1, 2]])['ok'], 'replanification');
    $assert($service->changeInterviewStatus(3, ['statut' => 'REALISE', 'compte_rendu' => 'Validé'])['ok'], 'replanification réalisée');
    $assert(! $service->saveEvaluation(['entretien_id' => 3, 'evaluateur_id' => 3, 'note' => 18, 'decision' => 'FAVORABLE', 'commentaire' => 'Non affecté'])['ok'], 'non-participant refusé');
    $assert($service->saveEvaluation(['entretien_id' => 3, 'evaluateur_id' => 2, 'note' => 17, 'decision' => 'FAVORABLE', 'commentaire' => 'Solide'])['ok'], 'participant évaluateur');
    $assert($service->saveInterview(['candidature_id' => 1, 'date_entretien' => '2099-01-13T09:00', 'type_entretien' => 'FINAL', 'lieu' => 'D', 'participant_ids' => [1]])['ok'], 'entretien final planifié');
    $assert(! $service->finalDecision(1, ['decision' => 'RETENUE'])['ok'], 'décision bloquée pendant entretien planifié');
    $assert($service->changeInterviewStatus(4, ['statut' => 'ANNULE'])['ok'], 'dernier entretien annulé');
    $assert($service->finalDecision(1, ['decision' => 'RETENUE'])['ok'], 'décision finale');
    $assert($db->table('candidature')->where(['id' => 1, 'statut' => 'RETENUE'])->countAllResults() === 1, 'sortie Bloc 3 disponible');
    $assert(! $service->changeApplicationStatus(1, ['statut' => 'PRESELECTIONNEE'])['ok'], 'statut final irréversible');
    $assert($db->table('historique_recrutement')->countAllResults() >= 12, 'historique transactionnel alimenté');

    echo "Bloc 2 PostgreSQL: {$tests} assertions réussies dans le schéma temporaire {$schema}." . PHP_EOL;
} catch (Throwable $e) {
    $failure = $e;
} finally {
    $admin->query("DROP SCHEMA IF EXISTS {$quotedSchema} CASCADE");
}

if ($failure !== null) {
    throw $failure;
}
