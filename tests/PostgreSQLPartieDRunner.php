<?php

declare(strict_types=1);

use App\Database\Migrations\CreatePartieDTables;
use App\Services\Bloc6\AnomaliesService;
use App\Services\Bloc6\TempsTravailleService;
use App\Services\Bloc7\AbsencesService;
use App\Services\Bloc7\TypesCongesService;
use CodeIgniter\Boot;
use CodeIgniter\Database\BaseConnection;
use CodeIgniter\HTTP\Files\UploadedFile;
use Config\Database;
use Config\Paths;

error_reporting(E_ALL);
ini_set('display_errors', '1');

define('ENVIRONMENT', 'testing');
define('CI_DEBUG', true);
define('HOMEPATH', dirname(__DIR__) . DIRECTORY_SEPARATOR);
define('CONFIGPATH', HOMEPATH . 'app/Config/');
define('PUBLICPATH', HOMEPATH . 'public/');
require CONFIGPATH . 'Paths.php';
$paths = new Paths();
define('APPPATH', realpath($paths->appDirectory) . DIRECTORY_SEPARATOR);
define('ROOTPATH', HOMEPATH);
define('SYSTEMPATH', realpath($paths->systemDirectory) . DIRECTORY_SEPARATOR);
define('WRITEPATH', realpath($paths->writableDirectory) . DIRECTORY_SEPARATOR);
define('TESTPATH', HOMEPATH . 'tests/');
define('CIPATH', ROOTPATH);
define('FCPATH', PUBLICPATH);
define('SUPPORTPATH', TESTPATH . '_support/');
define('COMPOSER_PATH', '');
define('VENDORPATH', HOMEPATH . 'vendor/');
require SYSTEMPATH . 'Boot.php';
Boot::bootTest($paths);
require_once APPPATH . 'Database/Migrations/2026-11-08-120000_CreatePartieDTables.php';

$database = (string) (getenv('PARTIED_TEST_PG_DATABASE') ?: 'sirh');
$username = (string) getenv('PARTIED_TEST_PG_USER');
$password = (string) getenv('PARTIED_TEST_PG_PASSWORD');
$hostname = (string) (getenv('PARTIED_TEST_PG_HOST') ?: '127.0.0.1');
$port = (int) (getenv('PARTIED_TEST_PG_PORT') ?: 5432);
if ($username === '' || $password === '') {
    fwrite(STDERR, "Définissez PARTIED_TEST_PG_USER et PARTIED_TEST_PG_PASSWORD.\n");
    exit(2);
}

$baseConfig = [
    'DBDriver' => 'Postgre', 'hostname' => $hostname, 'port' => $port,
    'database' => $database, 'username' => $username, 'password' => $password,
    'DBPrefix' => '', 'DBDebug' => true, 'schema' => 'public', 'charset' => 'UTF8',
    'dateFormat' => ['date' => 'Y-m-d', 'datetime' => 'Y-m-d H:i:s', 'time' => 'H:i:s'],
];
$admin = Database::connect($baseConfig, false);
$admin->initialize();

echo "Inspection publique (lecture seule) :\n";
foreach (['employe', 'departement', 'planning_travail', 'pointage', 'type_conge', 'absence', 'anomalie_pointage', 'demande_conge'] as $table) {
    $exists = $admin->tableExists($table);
    echo '- ' . $table . ': ' . ($exists ? implode(', ', $admin->getFieldNames($table)) : 'ABSENTE') . PHP_EOL;
}

$schema = 'partie_d_test_' . bin2hex(random_bytes(5));
$quotedSchema = '"' . $schema . '"';
$admin->query("CREATE SCHEMA {$quotedSchema}");
$failure = null;
$tests = 0;

try {
    $testConfig = $baseConfig;
    $testConfig['schema'] = $schema;
    $db = Database::connect($testConfig, false);
    $db->query("SET search_path TO {$quotedSchema}");
    foreach ([
        'CREATE TABLE departement (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nom_departement VARCHAR(100) NOT NULL)',
        'CREATE TABLE employe (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, matricule VARCHAR(20), nom VARCHAR(100), prenom VARCHAR(100), departement_id BIGINT REFERENCES departement(id), actif BOOLEAN DEFAULT TRUE)',
        'CREATE TABLE planning_travail (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, employe_id BIGINT NOT NULL REFERENCES employe(id), date_travail DATE NOT NULL, horaire_id BIGINT, heure_debut_prevue TIME NOT NULL, heure_fin_prevue TIME NOT NULL, pause_minutes_prevue INTEGER DEFAULT 0, heures_prevues NUMERIC(6,2), est_jour_repos BOOLEAN DEFAULT FALSE, UNIQUE(employe_id, date_travail))',
        'CREATE TABLE pointage (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, employe_id BIGINT NOT NULL REFERENCES employe(id), date_pointage DATE NOT NULL, heure_entree TIME, heure_sortie TIME, pause_minutes INTEGER DEFAULT 0, temps_travaille_heures NUMERIC(6,2), retard_minutes INTEGER DEFAULT 0, heures_supplementaires NUMERIC(6,2), statut VARCHAR(30), motif_correction TEXT, cree_le TIMESTAMP DEFAULT CURRENT_TIMESTAMP, modifie_par BIGINT, UNIQUE(employe_id, date_pointage))',
        'CREATE TABLE demande_conge (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, employe_id BIGINT NOT NULL REFERENCES employe(id), date_debut DATE NOT NULL, date_fin DATE NOT NULL, statut VARCHAR(30) NOT NULL)',
    ] as $sql) {
        $db->query($sql);
    }

    (new CreatePartieDTables(Database::forge($db)))->up();
    // tableExists()/getFieldNames() keep a per-connection metadata cache.
    // The migration has just created the isolated schema, so refresh it before assertions.
    $db->resetDataCache();
    $assert = static function (bool $condition, string $message) use (&$tests): void {
        $tests++;
        if (! $condition) throw new RuntimeException("ÉCHEC PostgreSQL #{$tests}: {$message}");
    };
    $foreignKeysSql = file_get_contents(ROOTPATH . 'database/partie_d/complete_foreign_keys.sql');
    if ($foreignKeysSql === false) throw new RuntimeException('Script de réconciliation des clés étrangères illisible.');
    $db->query($foreignKeysSql);
    $db->query($foreignKeysSql);
    $assert(true, 'réconciliation des clés étrangères rejouable');

    foreach (['type_conge', 'absence', 'absence_historique', 'anomalie_pointage', 'anomalie_pointage_historique'] as $table) {
        $assert($db->tableExists($table), "table {$table} créée");
    }
    foreach (['fk_anomalie_planning', 'fk_anomalie_pointage', 'fk_absence_demande_conge'] as $constraint) {
        $count = (int) $db->query('SELECT count(*) AS total FROM pg_constraint WHERE conname = ?', [$constraint])->getRowArray()['total'];
        $assert($count === 1, "contrainte {$constraint} créée");
    }

    $db->table('departement')->insert(['nom_departement' => 'RH']);
    $db->table('employe')->insertBatch([
        ['matricule' => 'D-001', 'nom' => 'Rakoto', 'prenom' => 'Aina', 'departement_id' => 1, 'actif' => true],
        ['matricule' => 'D-002', 'nom' => 'Rabe', 'prenom' => 'Miora', 'departement_id' => 1, 'actif' => true],
    ]);
    $db->table('planning_travail')->insertBatch([
        ['employe_id' => 1, 'date_travail' => '2026-11-01', 'heure_debut_prevue' => '08:00', 'heure_fin_prevue' => '17:00', 'pause_minutes_prevue' => 60, 'heures_prevues' => 8, 'est_jour_repos' => false],
        ['employe_id' => 1, 'date_travail' => '2026-11-02', 'heure_debut_prevue' => '08:00', 'heure_fin_prevue' => '17:00', 'pause_minutes_prevue' => 60, 'heures_prevues' => 8, 'est_jour_repos' => false],
        ['employe_id' => 2, 'date_travail' => '2026-11-01', 'heure_debut_prevue' => '08:00', 'heure_fin_prevue' => '17:00', 'pause_minutes_prevue' => 0, 'heures_prevues' => 0, 'est_jour_repos' => true],
        ['employe_id' => 2, 'date_travail' => '2026-11-03', 'heure_debut_prevue' => '22:00', 'heure_fin_prevue' => '06:00', 'pause_minutes_prevue' => 30, 'heures_prevues' => 7.5, 'est_jour_repos' => false],
    ]);
    $db->table('pointage')->insertBatch([
        ['employe_id' => 1, 'date_pointage' => '2026-11-01', 'heure_entree' => '08:15', 'heure_sortie' => '18:00', 'pause_minutes' => 60],
        ['employe_id' => 2, 'date_pointage' => '2026-11-03', 'heure_entree' => '22:00', 'heure_sortie' => '06:00', 'pause_minutes' => 30],
    ]);

    $anomalies = new AnomaliesService($db);
    $assert($anomalies->detect('2026-11-01', '2026-11-03', new DateTimeImmutable('2026-11-05 12:00:00', new DateTimeZone('Indian/Antananarivo'))) === 2, 'retard et journée sans pointage détectés');
    $assert($anomalies->detect('2026-11-01', '2026-11-03', new DateTimeImmutable('2026-11-05 12:00:00', new DateTimeZone('Indian/Antananarivo'))) === 0, 'nouvelle détection sans doublon');
    $assert($db->table('anomalie_pointage')->countAllResults() === 2, 'unicité métier des anomalies');
    $missing = $db->table('anomalie_pointage')->where('type', 'JOURNEE_SANS_POINTAGE')->get()->getRowArray();
    $anomalies->treat((int) $missing['id'], 'REGULARISEE', 'Vérification RH effectuée', 1);
    $assert($db->table('anomalie_pointage_historique')->where('anomalie_id', $missing['id'])->countAllResults() === 1, 'régularisation historisée');

    $summary = (new TempsTravailleService($db))->summary('2026-11-01', '2026-11-03');
    $byEmployee = array_column($summary, null, 'employe_id');
    $assert($byEmployee[1]['worked_minutes'] === 525 && $byEmployee[1]['planned_minutes'] === 960, 'temps net, pause et journée manquante calculés');
    $assert($byEmployee[2]['worked_minutes'] === 450, 'horaire traversant minuit calculé');

    $types = new TypesCongesService($db);
    $typeId = $types->save(['code' => 'MALADIE', 'libelle' => 'Maladie', 'actif' => '1', 'justificatif_obligatoire' => '0', 'mode_decompte' => 'A_DEFINIR'], 1);
    $absences = new AbsencesService($db);
    $absenceId = $absences->save(['employe_id' => 1, 'type_conge_id' => $typeId, 'date_debut' => '2026-11-10', 'date_fin' => '2026-11-11', 'motif' => 'Maladie', 'statut' => 'ENREGISTREE'], null, 1);
    $assert($absenceId > 0, 'absence réelle créée');
    $overlapRejected = false;
    try {
        $absences->save(['employe_id' => 1, 'date_debut' => '2026-11-11', 'date_fin' => '2026-11-12', 'motif' => 'Chevauchement', 'statut' => 'ENREGISTREE'], null, 1);
    } catch (InvalidArgumentException) {
        $overlapRejected = true;
    }
    $assert($overlapRejected, 'chevauchement d’absences refusé');
    $types->disable($typeId, 1);
    $assert($db->table('type_conge')->where('id', $typeId)->countAllResults() === 1, 'type utilisé conservé après désactivation');

    $uploadDirectory = WRITEPATH . 'uploads' . DIRECTORY_SEPARATOR . 'absences';
    $fakeUpload = new UploadedFile(WRITEPATH . 'fake-partie-d-upload.tmp', 'preuve.pdf', 'application/pdf', 8, UPLOAD_ERR_OK);
    $failingService = new class($db) extends AbsencesService {
        protected function storeFile(?UploadedFile $file): array
        {
            $directory = WRITEPATH . 'uploads' . DIRECTORY_SEPARATOR . 'absences';
            if (! is_dir($directory)) mkdir($directory, 0700, true);
            $path = $directory . DIRECTORY_SEPARATOR . 'partie-d-failure-test.pdf';
            file_put_contents($path, '%PDF-1.4');
            return ['justificatif_nom_original' => 'preuve.pdf', 'justificatif_nom_stocke' => basename($path), 'justificatif_mime' => 'application/pdf', 'justificatif_taille' => 8, '_stored_path' => $path];
        }
    };
    $db->query('DROP TABLE absence_historique');
    $db->resetDataCache();
    $sqlFailure = false;
    try {
        $failingService->save(['employe_id' => 2, 'date_debut' => '2026-11-15', 'date_fin' => '2026-11-15', 'motif' => 'Test SQL', 'statut' => 'ENREGISTREE'], $fakeUpload, 1);
    } catch (Throwable) {
        $sqlFailure = true;
    }
    $assert($sqlFailure && ! is_file($uploadDirectory . DIRECTORY_SEPARATOR . 'partie-d-failure-test.pdf'), 'justificatif supprimé après échec SQL');

    $rollbackBlocked = false;
    try {
        (new CreatePartieDTables(Database::forge($db)))->down();
    } catch (RuntimeException) {
        $rollbackBlocked = true;
    }
    $db->resetDataCache();
    $assert($rollbackBlocked && $db->tableExists('absence'), 'rollback destructif bloqué');

    echo "Partie D PostgreSQL : {$tests} assertions réussies dans le schéma temporaire {$schema}." . PHP_EOL;
} catch (Throwable $e) {
    $failure = $e;
} finally {
    $admin->query("DROP SCHEMA IF EXISTS {$quotedSchema} CASCADE");
}

if ($failure !== null) throw $failure;
